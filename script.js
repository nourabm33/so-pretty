const getSavedLanguage = () => localStorage.getItem("soPrettyLanguage") || document.documentElement.lang || "it";

function applyLanguage(language) {
  const dictionary = translations[language] || translations.it;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (dictionary[key]) element.innerHTML = dictionary[key];
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === language);
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  localStorage.setItem("soPrettyLanguage", language);
}

function setupNavigation() {
  const header = document.querySelector("[data-header]");
  const toggle = document.querySelector("[data-nav-toggle]");
  const menu = document.querySelector("[data-nav-menu]");
  const updateHeader = () => header?.classList.toggle("scrolled", window.scrollY > 24);
  updateHeader();
  window.addEventListener("scroll", updateHeader, { passive: true });

  toggle?.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-expanded", String(!isOpen));
    menu?.classList.toggle("open", !isOpen);
    document.body.classList.toggle("nav-open", !isOpen);
  });

  menu?.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      toggle?.setAttribute("aria-expanded", "false");
      menu.classList.remove("open");
      document.body.classList.remove("nav-open");
    });
  });
}

function setupRevealAnimations() {
  const elements = document.querySelectorAll(".reveal");
  if (!elements.length) return;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.16 });
  elements.forEach((element) => observer.observe(element));
}

function setupParallax() {
  const heroBg = document.querySelector("[data-parallax]");
  if (!heroBg || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  window.addEventListener("scroll", () => {
    const offset = Math.min(window.scrollY * 0.12, 90);
    heroBg.style.transform = `translateY(${offset}px) scale(1.06)`;
  }, { passive: true });
}

function setupGalleryFilters() {
  const filters = document.querySelectorAll("[data-filter]");
  const items = document.querySelectorAll("[data-category]");
  filters.forEach((filter) => {
    filter.addEventListener("click", () => {
      filters.forEach((button) => button.classList.remove("active"));
      filter.classList.add("active");
      const category = filter.dataset.filter;
      items.forEach((item) => {
        item.classList.toggle("hidden", category !== "all" && item.dataset.category !== category);
      });
    });
  });
}

function setupLightbox() {
  const modal = document.querySelector("[data-lightbox-modal]");
  const image = document.querySelector("[data-lightbox-image]");
  const caption = document.querySelector("[data-lightbox-caption]");
  const close = document.querySelector("[data-lightbox-close]");
  if (!modal || !image || !caption) return;

  const closeModal = () => {
    modal.classList.remove("open");
    modal.setAttribute("aria-hidden", "true");
    image.classList.remove("zoomed");
    image.removeAttribute("src");
    document.body.classList.remove("lightbox-open");
  };

  document.querySelectorAll("[data-lightbox]").forEach((trigger) => {
    trigger.addEventListener("click", () => {
      image.src = trigger.dataset.lightbox;
      image.alt = trigger.querySelector("img")?.alt || trigger.dataset.title || "So Pretty image";
      caption.textContent = trigger.dataset.title || "";
      modal.classList.add("open");
      modal.setAttribute("aria-hidden", "false");
      document.body.classList.add("lightbox-open");
    });
  });

  image.addEventListener("click", () => image.classList.toggle("zoomed"));
  close?.addEventListener("click", closeModal);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) closeModal();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && modal.classList.contains("open")) closeModal();
  });
}

